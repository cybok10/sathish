#!/usr/bin/env node
/**
 * Writes `server/schema.sql` from `server/schema.js`.
 *
 * The copy you paste into the Supabase SQL editor is generated from the
 * same source the app applies at boot, so the two cannot drift.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

const { SCHEMA_SQL, SCHEMA_VERSION } = await import(
  path.join(root, "server", "schema.js")
);

const header = `-- Generated by \`npm run schema:sql\` from server/schema.js — do not edit.
-- Schema version ${SCHEMA_VERSION}.
--
-- Paste this into the Supabase SQL editor to create the tables, or let the
-- app apply it on first boot (the DDL is idempotent).

`;

const target = path.join(root, "server", "schema.sql");
fs.writeFileSync(target, header + SCHEMA_SQL.trimStart() + "\n");
console.log(`written: ${target}`);
